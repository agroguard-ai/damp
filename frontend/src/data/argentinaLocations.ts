export function getProvinces(): string[] {
  return ARGENTINA_LOCATIONS.map((loc) => loc.province);
}

export function getDepartments(provinceName: string): string[] {
  const match = ARGENTINA_LOCATIONS.find((loc) => loc.province.toLowerCase() === provinceName.toLowerCase());
  return match ? match.departments : [];
}

/**
 * Helper to attempt matching a province string from Google Maps API to our normalized list
 */
export function matchProvince(rawProvince: string): string | null {
  if (!rawProvince) return null;
  const clean = rawProvince.toLowerCase().replace('provincia de ', '').trim();

  if (clean.includes('buenos aires') && !clean.includes('ciudad')) return 'Buenos Aires';
  if (clean.includes('ciudad') || clean.includes('caba') || clean.includes('autónoma'))
    return 'Ciudad Autónoma de Buenos Aires';

  const match = ARGENTINA_LOCATIONS.find((loc) => {
    const locClean = loc.province.toLowerCase();
    return locClean.includes(clean) || clean.includes(locClean);
  });

  return match ? match.province : null;
}

