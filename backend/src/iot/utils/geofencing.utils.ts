/**
 * Evaluates if a point (lat, lng) is inside a polygon using the Ray-Casting algorithm.
 * @param point The coordinate of the animal [latitude, longitude]
 * @param polygon The array of coordinates representing the zone boundaries [[lat1, lng1], [lat2, lng2], ...]
 */
export function isPointInPolygon(point: [number, number], polygon: [number, number][]): boolean {
  const [x, y] = point;
  let inside = false;

  for (let i = 0, j = polygon.length - 1; i < polygon.length; j = i++) {
    const xi = polygon[i][0];
    const yi = polygon[i][1];
    const xj = polygon[j][0];
    const yj = polygon[j][1];

    const intersect = yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi;

    if (intersect) {
      inside = !inside;
    }
  }

  return inside;
}
